//! Opt-in suppression of clone families that carry little review signal.

use crate::engine::RepositoryState;
use crate::operations::optional_bool;
use blazingly_json::Value;
use std::collections::HashMap;
use weavatrix_clone::CloneFamily;

#[derive(Clone, Copy)]
pub(super) struct LowSignalSuppression {
    pub(super) boilerplate: usize,
    pub(super) declarative: usize,
}

pub(super) fn suppress(
    state: &RepositoryState,
    args: &Value,
    families: Vec<CloneFamily>,
) -> Result<(Vec<CloneFamily>, LowSignalSuppression), String> {
    let include_boilerplate = optional_bool(args, "include_boilerplate")?.unwrap_or(false);
    // Clone review is high-recall by default. Callers may explicitly suppress
    // data-only catalogs, but absence of control flow is not enough to hide
    // model, schema, or contract duplication.
    let include_declarative = optional_bool(args, "include_declarative")?.unwrap_or(true);
    let mut sources = HashMap::<String, Vec<String>>::new();
    let mut generated_heads = HashMap::<String, bool>::new();
    let mut suppression = LowSignalSuppression {
        boilerplate: 0,
        declarative: 0,
    };
    let families = families
        .into_iter()
        .filter(|family| {
            if !include_boilerplate
                && family.members.iter().all(|member| {
                    is_boilerplate(&member.path)
                        || generated_client_file(state.root(), &member.path, &mut generated_heads)
                })
            {
                suppression.boilerplate += 1;
                return false;
            }
            if !include_declarative
                && family.members.iter().all(|member| {
                    !is_semantic_contract_path(&member.path)
                        && !has_control_flow(
                            state.root(),
                            &member.path,
                            member.span.start_line,
                            member.span.end_line,
                            &mut sources,
                        )
                })
            {
                suppression.declarative += 1;
                return false;
            }
            true
        })
        .collect();
    Ok((families, suppression))
}

fn is_boilerplate(path: &str) -> bool {
    let lower = path.to_ascii_lowercase();
    let file = lower.rsplit(['/', '\\']).next().unwrap_or(&lower);
    [
        ".router.",
        ".routes.",
        ".handlers.",
        ".gen.",
        ".generated.",
        ".pb.go",
    ]
    .iter()
    .any(|marker| file.contains(marker))
}

fn generated_client_head(head: &str) -> bool {
    let lower = head.to_ascii_lowercase();
    lower.contains("openapi-generator.tech")
        && (lower.contains("generated by") || lower.contains("automatically generated"))
}

fn generated_client_file(
    root: &std::path::Path,
    path: &str,
    heads: &mut HashMap<String, bool>,
) -> bool {
    *heads.entry(path.to_owned()).or_insert_with(|| {
        let mut file = match std::fs::File::open(root.join(path)) {
            Ok(file) => file,
            Err(_) => return false,
        };
        let mut buf = [0_u8; 512];
        let read = std::io::Read::read(&mut file, &mut buf).unwrap_or(0);
        generated_client_head(&String::from_utf8_lossy(&buf[..read]))
    })
}

fn is_semantic_contract_path(path: &str) -> bool {
    path.to_ascii_lowercase()
        .split(|character: char| !character.is_ascii_alphanumeric())
        .any(|word| {
            matches!(
                word,
                "model" | "models" | "schema" | "schemas" | "contract" | "contracts"
            )
        })
}

fn has_control_flow(
    root: &std::path::Path,
    path: &str,
    start_line: u32,
    end_line: u32,
    sources: &mut HashMap<String, Vec<String>>,
) -> bool {
    const MARKERS: &[&str] = &[
        "if ", "if(", "for ", "for(", "while ", "while(", "return", "=>", "function", "throw",
        "await ", "switch", "yield", "match ", "loop ", "?.",
    ];
    let lines = sources.entry(path.to_owned()).or_insert_with(|| {
        std::fs::read_to_string(root.join(path))
            .map(|text| text.lines().map(str::to_owned).collect())
            .unwrap_or_default()
    });
    let start = usize::try_from(start_line.saturating_sub(1)).unwrap_or(0);
    let end = usize::try_from(end_line).unwrap_or(0).min(lines.len());
    if start >= end {
        return true;
    }
    lines[start..end]
        .iter()
        .any(|line| MARKERS.iter().any(|marker| line.contains(marker)))
}

#[cfg(test)]
mod tests {
    use super::{
        generated_client_file, generated_client_head, is_boilerplate, is_semantic_contract_path,
    };
    use std::collections::HashMap;

    #[test]
    fn boilerplate_and_contract_paths_are_named() {
        assert!(is_boilerplate("src/app.router.ts"));
        assert!(is_boilerplate("src\\users.routes.js"));
        assert!(is_boilerplate("api.handlers.mjs"));
        assert!(is_boilerplate("src/client/api.gen.ts"));
        assert!(is_boilerplate("pkg/types.generated.go"));
        assert!(is_boilerplate("agent/agent.pb.go"));
        assert!(is_boilerplate("controller/controller_grpc.pb.go"));
        assert!(!is_boilerplate("server/srvhello/srvhello.go"));
        assert!(!is_boilerplate("src/client/api.ts"));
        assert!(!is_boilerplate("src/model.ts"));
        assert!(generated_client_head(
            "Generated by: https://openapi-generator.tech\nclass ApiTypeError:\n"
        ));
        assert!(!generated_client_head(
            "see https://openapi-generator.tech before writing a client\n"
        ));
        assert!(is_semantic_contract_path("src/models/user.ts"));
        assert!(is_semantic_contract_path("pkg/schema/v1.json"));
        assert!(is_semantic_contract_path("contracts/vault.rs"));
        assert!(!is_semantic_contract_path("src/util.ts"));
    }

    #[test]
    fn generated_client_file_reads_the_header_stamp() {
        let root = std::env::temp_dir().join(format!(
            "weavatrix-gen-{}-{}",
            std::process::id(),
            std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .unwrap_or_default()
                .as_nanos()
        ));
        std::fs::create_dir_all(&root).unwrap();
        std::fs::write(
            root.join("exceptions.py"),
            "Generated by: https://openapi-generator.tech\nclass ApiTypeError:\n",
        )
        .unwrap();
        std::fs::write(root.join("app.py"), "def core():\n    return 1\n").unwrap();
        let mut heads = HashMap::new();
        assert!(generated_client_file(&root, "exceptions.py", &mut heads));
        assert!(!generated_client_file(&root, "app.py", &mut heads));
        assert!(generated_client_file(&root, "exceptions.py", &mut heads));
        let _ = std::fs::remove_dir_all(&root);
    }
}
